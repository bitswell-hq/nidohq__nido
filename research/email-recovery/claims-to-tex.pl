#!/usr/bin/env perl
# Render the claim ledger as LaTeX for shared/claims.sty.
#
#   perl claims-to-tex.pl claims.yaml > build/gen/claims.tex
#
# Emits one \ClaimDefine{id}{status}{statement}{evidence} per entry, in ledger
# order, followed by \ClaimTableRows (the rows of the appendix table). Run
# check-claims.pl first; this script assumes a well-formed ledger.
use strict;
use warnings;
use YAML::Tiny;

my $ledger = shift or die "usage: $0 claims.yaml\n";
my $claims = YAML::Tiny->read($ledger)->[0]{claims};

sub tex {
    my $s = shift // '';
    $s =~ s/\s+/ /g;
    $s =~ s/^ | $//g;
    my %map = (
        '\\' => '\textbackslash{}', '{' => '\{', '}' => '\}', '$' => '\$',
        '&'  => '\&', '#' => '\#', '%' => '\%', '_' => '\_',
        '^'  => '\textasciicircum{}', '~' => '\textasciitilde{}',
    );
    $s =~ s/([\\{}\$&#%_^~])/$map{$1}/g;
    # The operator's name follows the document's anonymity switch (macros.tex).
    $s =~ s/\bNido\b/\\OpName{}/g;
    $s =~ s/\bNIDO\b/\\OpNameUpper{}/g;
    return $s;
}

# A TeX-escaped name or path that may break after each '/', '.' or '_'.
sub breakable {
    my $s = shift;
    $s =~ s{(/|\.|\\_)}{$1\\allowbreak{}}g;
    return $s;
}

sub evidence {
    my $ev = shift;
    return join('; ', map { evidence($_) } @$ev) if ref $ev eq 'ARRAY';
    return '' unless ref $ev eq 'HASH';
    return tex($ev->{assumption}) if defined $ev->{assumption};
    my $name = $ev->{lean} // $ev->{test};
    my $file = '\texttt{' . breakable(tex($ev->{file})) . '}';
    return defined $name ? '\texttt{' . breakable(tex($name)) . "} in $file" : $file;
}

print "% Generated by claims-to-tex.pl from claims.yaml. Do not edit.\n";
my @rows;
for my $c (@$claims) {
    my ($id, $status) = ($c->{id}, $c->{status});
    my ($st, $ev) = (tex($c->{statement}), evidence($c->{evidence}));
    print "\\ClaimDefine{$id}{$status}{$st}{$ev}\n";
    (my $shown = $id) =~ s/-/-\\allowbreak{}/g;    # let long ids wrap in the table
    push @rows, "\\ClaimRow{$id}{$shown}";
}
print "\\def\\ClaimTableRows{%\n", join("%\n", @rows), "%\n}\n";
