#!/usr/bin/env perl
# Render the evaluation's run-dependent figures as LaTeX for shared/claims.sty.
#
#   perl figures-to-tex.pl > build/gen/figures.tex
#
# Reads eval/results/figures.json, which eval/report.mjs writes from the attack
# run's results each time it regenerates the evaluation's README, and emits one
# \FigureDefine{name}{value}{millions, two decimals}{millions, one decimal} per
# figure. The documents print them with \fig{name}, \figM{name} and
# \figM[1]{name}, and the claim ledger with {{name}} and {{name:m}}, so a
# re-run of the attack suite regenerates every copy with its evidence.
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Spec;
use JSON::PP;

my $here = File::Spec->rel2abs(dirname(__FILE__));
my $path = shift // "$here/eval/results/figures.json";
open my $fh, '<:raw', $path or die "error: cannot read $path: $!\n";
my $doc = JSON::PP->new->utf8->decode(do { local $/; <$fh> });
close $fh;
my $figures = $doc->{figures};
die "error: $path has no 'figures' map\n" unless ref $figures eq 'HASH';

sub grouped {
    my $v = shift;
    my $s = sprintf '%d', $v;
    1 while $s =~ s/^(-?\d+)(\d{3})/$1\{,\}$2/;
    return $s;
}

print "% Generated by figures-to-tex.pl from eval/results/figures.json. Do not edit.\n";
for my $name (sort keys %$figures) {
    my $v = $figures->{$name};
    die "error: figure '$name' is not an integer\n" unless defined $v && !ref $v && $v =~ /^-?\d+$/;
    die "error: figure name '$name' must match [a-z][a-z0-9-]*\n" unless $name =~ /^[a-z][a-z0-9-]*$/;
    printf "\\FigureDefine{%s}{%s}{%.2f}{%.1f}\n", $name, grouped($v), $v / 1e6, $v / 1e6;
}
