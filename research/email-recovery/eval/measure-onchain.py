#!/usr/bin/env python3
"""On-chain cost of one email approval with a real proof, per launch domain.

Runs `crates/integration-tests/tests/it/email_proofs.rs` (one
`submit_guardian` per launch domain, plus the 124-byte address at WEB.DE),
collects the JSON object each test prints, and rewrites the generated block
of onchain.md next to this script. Needs the contract wasm
(`just build-contracts`) and the committed email fixtures.

    python3 research/email-recovery/eval/measure-onchain.py
"""

import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
LIMIT = 400_000_000


def main():
    out = subprocess.run(
        ["cargo", "test", "-p", "nido-integration-tests", "--test", "it", "email_proofs",
         "--", "--nocapture", "--test-threads=1"],
        cwd=REPO, check=True, capture_output=True, text=True,
    ).stdout
    marker = '{"case":"submit_guardian'
    rows = [json.loads(l[l.index(marker):]) for l in out.splitlines() if marker in l]
    if len(rows) != 12:
        sys.exit(f"expected 12 measured approvals, got {len(rows)}")
    rows.sort(key=lambda r: (not r["label"].startswith("provider-"), r["label"]))

    host_lines, tx_lines = [], []
    for r in rows:
        h, t = r["host"], r["tx"]
        name = r["domain"] if r["label"].startswith("provider-") else f"{r['domain']}, {r['address_bytes']}-byte address and display name"
        host_lines.append(
            f"| {name} | {h['instructions']:,} ({h['instructions'] * 100 / LIMIT:.1f}%) | {h['mem_bytes']:,} | "
            f"{h['read_entries']} | {h['write_entries']} | {h['write_bytes']:,} | {h['fee_no_rent']:,} |"
        )
        tx_lines.append(
            f"| {name} | {t['instructions']:,} | {t['read_only']} + {t['read_write']} | {t['write_bytes']:,} | "
            f"{t['auth_entry_bytes']:,} | {t['envelope_bytes']:,} | {t['fee_no_rent']:,} |"
        )
    block = "\n".join([
        f"Generated by `research/email-recovery/eval/measure-onchain.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC",
        "from `crates/integration-tests/tests/it/email_proofs.rs`.",
        "",
        "On the test host (`cost_estimate()` of the `submit_guardian` invocation; the host enforces",
        "the SDK's mainnet limits on it):",
        "",
        "| Domain | Instructions (of 400,000,000) | Memory bytes | Entries read | Entries written | Bytes written | Resource fee without rent, SDK's 2026-07-10 fee snapshot (stroops) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *host_lines,
        "",
        "As a transaction (`nido_integration_tests::transaction::measure`: a fresh host over a ledger",
        "snapshot, the signed authorization entry enforced):",
        "",
        "| Domain | Instructions | Footprint (read-only + read-write) | Bytes written | Authorization entry bytes | Signed envelope bytes | Resource fee without rent, SDK's 2026-07-10 fee snapshot (stroops) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *tx_lines,
        "",
        "Raw rows:",
        "",
        "```json",
        *[json.dumps(r, sort_keys=True) for r in rows],
        "```",
    ])
    doc = HERE / "onchain.md"
    text = doc.read_text()
    begin = "<!-- BEGIN GENERATED by measure-onchain.py; do not edit -->"
    end = "<!-- END GENERATED -->"
    pattern = re.compile(re.escape(begin) + ".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        sys.exit(f"{doc} has no generated-block markers")
    doc.write_text(pattern.sub(lambda _: f"{begin}\n{block}\n{end}", text))
    print(block)


if __name__ == "__main__":
    main()
