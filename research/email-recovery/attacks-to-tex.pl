#!/usr/bin/env perl
# Render the evaluation's attack results as LaTeX for the paper's appendix.
#
#   perl attacks-to-tex.pl > build/gen/attacks.tex
#
# Reads eval/results/attacks-local.json (the local-network run) and
# eval/results/attacks-test-host.jsonl (the registry scenarios run on the
# integration-test host), the files eval/report.mjs renders into
# eval/README.md, and emits:
#
#   \AttackTableA, \AttackTableB  the scenario rows, split in two by class
#   \AttackCircuitRows            the circuit's verdict on each adversarial email
#
# Exits non-zero if a row's observed outcome differs from its expected one, if
# a circuit case differs from the outcome the unit attack suite pins, or if a
# string holds a character it cannot typeset, so the paper never shows a
# result the run did not produce.
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Spec;
use JSON::PP;

my $here = File::Spec->rel2abs(dirname(__FILE__));
my $results = "$here/eval/results";

sub slurp {
    my $path = shift;
    open my $fh, '<:raw', $path or die "error: cannot read $path: $!\n";
    local $/;
    return <$fh>;
}

my $json = JSON::PP->new->utf8;
my $local = $json->decode(slurp("$results/attacks-local.json"));
my @host = map { $json->decode($_) } grep { /\S/ } split /\n/, slurp("$results/attacks-test-host.jsonl");

# The class order and names of eval/report.mjs.
my @classes = (
    [forged => 'Forged emails'],
    [replay => 'Replayed emails and proofs'],
    [statement => 'Wrong account or new key in the statement'],
    [registry => 'Stale or malicious registry keys'],
    [inbox => 'Compromised inbox'],
    [quirks => 'Provider header quirks'],
    ['front-running' => 'Front-running'],
    [privacy => 'Privacy on chain'],
);
my %known = map { $_->[0] => 1 } @classes;

my %unicode = (
    "\x{03c3}" => '$\sigma$', "\x{2014}" => '---', "\x{2013}" => '--',
    "\x{2019}" => q('), "\x{2018}" => q(`), "\x{201c}" => q(``), "\x{201d}" => q(''),
);

sub tex {
    my $s = shift // '';
    $s =~ s/\s+/ /g;
    $s =~ s/^ | $//g;
    my %map = (
        '\\' => '\textbackslash{}', '{' => '\{', '}' => '\}', '$' => '\$',
        '&'  => '\&', '#' => '\#', '%' => '\%', '_' => '\_\allowbreak{}',
        '^'  => '\textasciicircum{}', '~' => '\textasciitilde{}',
        '<'  => '\textless{}', '>' => '\textgreater{}',
    );
    $s =~ s/([\\{}\$&#%_^~<>])/$map{$1}/g;
    $s =~ s/([^\x00-\x7f])/exists $unicode{$1} ? $unicode{$1}
        : die sprintf("error: cannot typeset U+%04X in '%s'\n", ord $1, $s)/ge;
    return $s;
}

# Hyphenated identifiers break after each hyphen.
sub ident { (my $s = tex(shift)) =~ s/-/-\\allowbreak{}/g; return $s }

my @rows = (@{ $local->{rows} }, @host);
my @problems;
for my $r (@rows) {
    push @problems, "unknown class '$r->{class}' in $r->{scenario}" unless $known{ $r->{class} };
    push @problems, "$r->{scenario}: observed '$r->{observed}', expected '$r->{expected}'"
        unless $r->{observed} eq $r->{expected};
}
for my $c (@{ $local->{circuitCases} }) {
    push @problems, "circuit case $c->{id}: '$c->{outcome}' differs from the pinned '$c->{pinned}'"
        unless $c->{outcome} eq $c->{pinned};
}
if (@problems) {
    print STDERR "attacks-to-tex: $_\n" for @problems;
    exit 1;
}

sub row {
    my $r = shift;
    my $scenario = '\texttt{' . ident($r->{scenario}) . '}' . ($r->{note} ? ': ' . tex($r->{note}) : '');
    my $where = $r->{network} eq 'local' ? 'local' : 'host';
    return join(' & ', $scenario, tex($r->{expected}), tex($r->{layer}), $r->{property}, $where)
        . " \\\\\n";
}

sub table {
    my @keys = @_;
    my $out = '';
    for my $c (@classes) {
        my ($key, $name) = @$c;
        next unless grep { $_ eq $key } @keys;
        my @in = grep { $_->{class} eq $key } @rows;
        next unless @in;
        $out .= "\\multicolumn{5}{\@{}l}{\\textbf{" . tex($name) . '} (' . scalar(@in) . ")} \\\\\n";
        $out .= row($_) for @in;
    }
    return $out;
}

print "% Generated by attacks-to-tex.pl from eval/results. Do not edit.\n";
print "\\def\\AttackTableA{%\n", table(qw(forged replay statement)), "}\n";
print "\\def\\AttackTableB{%\n", table(qw(registry inbox quirks front-running privacy)), "}\n";
print "\\def\\AttackCircuitRows{%\n";
for my $c (@{ $local->{circuitCases} }) {
    (my $verdict = $c->{verdict}) =~ s/^valid-dkim-but-must-be-rejected-by-circuit$/valid, must refuse/;
    $verdict =~ s/^valid-dkim-and-must-be-accepted$/valid, must accept/;
    $verdict =~ s/^invalid-dkim$/invalid/;
    print join(' & ', '\texttt{' . ident($c->{id}) . '}', tex($verdict), tex($c->{tree}), tex($c->{outcome})),
        " \\\\\n";
}
print "}\n";
