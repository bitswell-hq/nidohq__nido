#!/usr/bin/env bash
# The document build proper: `make -C paper` runs it inside the pinned TeX Live
# image with the repository mounted at /repo.
#
#   bash tools/build.sh [REVIEW]     # REVIEW=1 (default): anonymous review mode
#
# 1. checks the claim ledger (claims.yaml) against the repository and the
#    documents, with the checker research/email-recovery/ also uses;
# 2. generates build/gen/claims.tex from the ledger;
# 3. builds the paper and the slides with latexmk -Werror, then scans the logs,
#    so an undefined reference or citation, or a missing bibliography entry,
#    fails the build.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
here="$PWD"
repo="$(cd .. && pwd)"
build="$here/build"
review="${1:-1}"
ledger_tools="$repo/research/email-recovery"

echo "==> claim ledger"
perl "$ledger_tools/check-claims.pl" --ledger "$here/claims.yaml" \
    --sources "$here/sections" --sources "$here/slides" --sources "$here/figures" \
    --repo "$repo"
mkdir -p "$build/gen"
perl "$ledger_tools/claims-to-tex.pl" "$here/claims.yaml" >"$build/gen/claims.tex.tmp"
mv "$build/gen/claims.tex.tmp" "$build/gen/claims.tex"

echo "==> line counts"
# Non-blank lines that do not start with // for Rust; non-blank lines for Lean.
rs() { cat "$@" | grep -cv '^[[:space:]]*\(//.*\)\?$' || true; }
lean() { cat "$@" | grep -cv '^[[:space:]]*$' || true; }
commas() {
    local n="$1" out=""
    while [ "${#n}" -gt 3 ]; do out=",${n: -3}$out"; n="${n:0:${#n}-3}"; done
    printf '%s' "$n$out"
}
loc() { printf '\\newcommand\\%s{%s}\n' "$1" "$(commas "$2")"; }
f="$repo/formal/AttenuatingGrants"
{
    echo "% Generated by tools/build.sh. Do not edit."
    loc LocGrantEval "$(rs "$repo"/crates/grant-eval/src/*.rs)"
    loc LocModel "$(lean "$f/Grant.lean" "$f"/Vocab/*.lean)"
    loc LocBudget "$(lean "$f/Budget.lean")"
    loc LocCost "$(lean "$f"/Cost/*.lean)"
    loc LocEquiv "$(lean "$f"/Equiv/*.lean)"
    loc LocExtracted "$(lean "$f"/Extracted/*.lean)"
    loc LocSigner "$(rs "$repo"/contracts/grant-signer/src/*.rs)"
    loc LocSignerActions "$(rs "$repo/contracts/grant-signer/src/actions.rs")"
    loc LocSignerContract "$(rs "$repo/contracts/grant-signer/src/contract.rs")"
    loc LocComponent "$(rs "$repo"/crates/grant-component/src/*.rs)"
    loc LocHost "$(rs "$repo"/crates/agent-host/src/*.rs)"
    loc LocHostFs "$(rs "$repo/crates/agent-host/src/fs.rs")"
    loc LocHostNet "$(rs "$repo/crates/agent-host/src/net.rs")"
    loc LocHostSign "$(rs "$repo/crates/agent-host/src/sign.rs")"
    loc LocRelay "$(rs "$repo"/crates/grant-relay/src/*.rs)"
    loc LocRelayActions "$(rs "$repo/crates/grant-relay/src/actions.rs")"
} >"$build/gen/loc.tex"
cat "$build/gen/loc.tex"

# Both documents find grants.sty, the figures, the generated ledger, the
# ledger's style file and the bibliography.
export TEXINPUTS=".:$here:$here/figures:$build/gen:$ledger_tools/shared:"
export BIBINPUTS=".:$here:"

if [ "$review" = 1 ]; then
    options='sigconf,anonymous,review'
else
    options='sigconf'
fi

compile() {
    local src="$1" name="$2" out="$build/$2" pretex="${3:-}"
    (cd "$src" && latexmk -r "$here/latexmkrc" -Werror ${pretex:+-usepretex="$pretex"} \
        -outdir="$out" main.tex)
    if grep -nE "(Reference|Citation) .* undefined|There were undefined (references|citations)|I didn't find a database entry" \
        "$out/main.log" "$out"/main.blg 2>/dev/null; then
        echo "error: $name has undefined references or citations (see above)" >&2
        exit 1
    fi
    cp "$out/main.pdf" "$build/$name.pdf"
}

echo "==> paper ($options)"
compile "$here" paper "\\def\\PaperClassOptions{$options}"
echo "==> slides"
compile "$here/slides" slides

echo "built: $build/paper.pdf $build/slides.pdf"
