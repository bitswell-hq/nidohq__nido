//! `dns-attestation-mock`: fixtures from the TEST-ONLY DNS attester mock.
//!
//! ```text
//! dns-attestation-mock key-hash --txt <string> [--txt <string> ...]
//! dns-attestation-mock attest --registry <C... | 64 hex> --domain <d> --selector <s>
//!     (--txt <string> ... | --absent) [--key-hash <64 hex>]
//!     --observed-at <unix seconds> --resolver <id> [--resolver <id> ...] --attester <index>
//! dns-attestation-mock noir-inputs
//! ```
//!
//! `--txt` takes the strings of the record's TXT RR in order (they are
//! concatenated, RFC 6376 §3.6.2.2). `attest` without `--key-hash` attests
//! the key the record publishes; with it, whether the record publishes that
//! key (for a retirement, `--absent` or a blanked record). Output is JSON
//! with hex fields, ready for `DkimRegistry::attest`. `noir-inputs` prints
//! `contracts/dkim-registry/vectors/src/inputs.nr` from the fixture records.

use nido_dns_attestation_mock::{
    contract_id_of, fixture, key_hash, modulus_2048, observe, parse_txt, TestAttester,
};
use std::fmt::Write as _;
use std::process::ExitCode;

struct Args(Vec<String>);

impl Args {
    fn all(&self, flag: &str) -> Vec<&str> {
        self.0
            .windows(2)
            .filter(|w| w[0] == flag)
            .map(|w| w[1].as_str())
            .collect()
    }

    fn one(&self, flag: &str) -> Result<&str, String> {
        match self.all(flag).as_slice() {
            [v] => Ok(v),
            [] => Err(format!("missing {flag}")),
            _ => Err(format!("{flag} given twice")),
        }
    }

    fn has(&self, flag: &str) -> bool {
        self.0.iter().any(|a| a == flag)
    }
}

fn hex32(s: &str) -> Result<[u8; 32], String> {
    let v = hex::decode(s).map_err(|e| format!("{s}: {e}"))?;
    v.try_into().map_err(|_| format!("{s}: not 32 bytes"))
}

fn record_key(strings: &[&str]) -> Result<([u8; 256], [u8; 32]), String> {
    let record = parse_txt(strings).map_err(|e| format!("record: {e:?}"))?;
    let n = modulus_2048(&record).ok_or("record: not an RSA-2048 key")?;
    Ok((n, key_hash(&n)))
}

fn key_hash_cmd(args: &Args) -> Result<serde_json::Value, String> {
    let (n, kh) = record_key(&args.all("--txt"))?;
    Ok(serde_json::json!({ "modulus": hex::encode(n), "key_hash": hex::encode(kh) }))
}

fn attest_cmd(args: &Args) -> Result<serde_json::Value, String> {
    let registry = args.one("--registry")?;
    let registry = if registry.starts_with('C') {
        contract_id_of(registry)
    } else {
        hex32(registry)?
    };
    let txt = args.all("--txt");
    let txt = if args.has("--absent") {
        None
    } else {
        Some(txt.as_slice())
    };
    let wanted = match args.all("--key-hash").as_slice() {
        [h] => hex32(h)?,
        [] => record_key(txt.ok_or("--absent needs --key-hash")?)?.1,
        _ => return Err("--key-hash given twice".into()),
    };
    let observed_at: u64 = args
        .one("--observed-at")?
        .parse()
        .map_err(|e| format!("--observed-at: {e}"))?;
    let index: u8 = args
        .one("--attester")?
        .parse()
        .map_err(|e| format!("--attester: {e}"))?;
    let obs = observe(
        args.one("--domain")?,
        args.one("--selector")?,
        txt,
        wanted,
        observed_at,
        &args.all("--resolver"),
    );
    let signed = TestAttester::new(index).attest(&registry, &obs);
    Ok(serde_json::json!({
        "attester": hex::encode(signed.attester),
        "attestation": hex::encode(&signed.bytes),
        "signature": hex::encode(signed.signature),
        "key_hash": hex::encode(obs.key_hash),
        "observed_live": obs.observed_live,
    }))
}

fn noir_array(bytes: &[u8]) -> String {
    let items: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
    format!("[{}]", items.join(", "))
}

fn noir_inputs() -> Result<String, String> {
    let mut out = String::from(
        "// Generated by `just dkim-registry-vectors` (the mock's `noir-inputs`, then\n\
         // `nargo fmt`) from crates/dns-attestation-mock/testdata/records.json: the\n\
         // three RSA-2048 test moduli (256 big-endian bytes) and their domains.\n",
    );
    for (name, ident) in [("rsa2048-a", "A"), ("rsa2048-b", "B"), ("rsa2048-c", "C")] {
        let rec = fixture(name);
        let (n, _) = record_key(&rec.strings())?;
        let mut domain = rec.domain.as_bytes().to_vec();
        let len = domain.len();
        domain.resize(62, 0);
        write!(
            out,
            "\npub global MODULUS_{ident}: [u8; 256] = {};\npub global DOMAIN_{ident}: [u8; 62] = {};\npub global DOMAIN_{ident}_LEN: u32 = {len};\n",
            noir_array(&n),
            noir_array(&domain),
        )
        .expect("writing to a String");
    }
    Ok(out)
}

fn main() -> ExitCode {
    let given: Vec<String> = std::env::args().skip(1).collect();
    let Some((cmd, rest)) = given.split_first() else {
        eprintln!(
            "usage: dns-attestation-mock key-hash | attest | noir-inputs (see the crate docs)"
        );
        return ExitCode::from(2);
    };
    let args = Args(rest.to_vec());
    let result = match cmd.as_str() {
        "key-hash" => key_hash_cmd(&args).map(|v| v.to_string()),
        "attest" => attest_cmd(&args).map(|v| v.to_string()),
        "noir-inputs" => noir_inputs(),
        other => Err(format!("unknown command {other}")),
    };
    match result {
        Ok(out) => {
            println!("{out}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("dns-attestation-mock: {e}");
            ExitCode::FAILURE
        }
    }
}
