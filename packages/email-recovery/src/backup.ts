/**
 * The two backups of `account_code` (`docs/email-recovery/spec.md` §5.6),
 * kept in one module because which of them a wallet offers is still open
 * (§13 question 4):
 *
 * (a) A passphrase-encrypted copy for the enrollment email's body, so it
 *     sits in the user's Sent folder:
 *
 *       -----BEGIN NIDO RECOVERY CODE-----
 *       v1.<base64url-no-padding( salt || nonce || ciphertext )>
 *       -----END NIDO RECOVERY CODE-----
 *
 *       key        = Argon2id(passphrase, salt, t = 3, m = 65536 KiB, p = 4, 32 octets)
 *       ciphertext = AES-256-GCM(key, nonce, account_code,
 *                                aad = "nido/email-recovery/v1/code-backup" || account contract id)
 *
 *     The passphrase is five words drawn uniformly from the EFF large
 *     wordlist, generated by the wallet (about 64.6 bits).
 *
 * (b) A recovery kit: the 16 octets as 26 characters of RFC 4648 base32
 *     without padding, in groups of four.
 */

import { argon2idAsync } from '@noble/hashes/argon2.js';
import { buf, concat, fromBase64Url, randomBytes, toBase64Url, utf8 } from './bytes.js';
import { EFF_LARGE_WORDLIST } from './effWordlist.js';

export const BACKUP_AAD_LABEL = 'nido/email-recovery/v1/code-backup';
export const BACKUP_BEGIN = '-----BEGIN NIDO RECOVERY CODE-----';
export const BACKUP_END = '-----END NIDO RECOVERY CODE-----';
/** RFC 9106 §4, second recommended option. */
export const BACKUP_ARGON2 = { t: 3, m: 65_536, p: 4, dkLen: 32 } as const;
export const PASSPHRASE_WORDS = 5;

const CODE_LEN = 16;
const SALT_LEN = 16;
const NONCE_LEN = 12;

export class BackupError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'BackupError';
  }
}

/** A uniform index below `n` from 16-bit random draws (rejection sampling). */
function uniform(n: number): number {
  const limit = 65_536 - (65_536 % n);
  for (;;) {
    const [r] = crypto.getRandomValues(new Uint16Array(1));
    if (r! < limit) return r! % n;
  }
}

/** Five words drawn uniformly from the EFF large wordlist, lowercase, separated by single spaces. */
export function generatePassphrase(words: readonly string[] = EFF_LARGE_WORDLIST): string {
  return Array.from({ length: PASSPHRASE_WORDS }, () => words[uniform(words.length)]).join(' ');
}

/** A passphrase as the user typed it back: case and runs of whitespace forgiven. */
export function normalizePassphrase(s: string): string {
  return s.trim().toLowerCase().split(/\s+/).join(' ');
}

async function backupKey(passphrase: string, salt: Uint8Array): Promise<CryptoKey> {
  const raw = await argon2idAsync(utf8(passphrase), salt, { ...BACKUP_ARGON2 });
  return crypto.subtle.importKey('raw', buf(raw), 'AES-GCM', false, ['encrypt', 'decrypt']);
}

function checkLengths(accountCode: Uint8Array, accountId: Uint8Array) {
  if (accountCode.length !== CODE_LEN) throw new BackupError('account_code is 16 octets');
  if (accountId.length !== 32) throw new BackupError('an account contract id is 32 octets');
}

/** The (a) block for `accountCode`, bound to the account `accountId`. */
export async function encryptBackup(
  accountCode: Uint8Array,
  passphrase: string,
  accountId: Uint8Array,
  rand: { salt?: Uint8Array; nonce?: Uint8Array } = {},
): Promise<string> {
  checkLengths(accountCode, accountId);
  const salt = rand.salt ?? randomBytes(SALT_LEN);
  const nonce = rand.nonce ?? randomBytes(NONCE_LEN);
  const key = await backupKey(normalizePassphrase(passphrase), salt);
  const ct = new Uint8Array(
    await crypto.subtle.encrypt(
      { name: 'AES-GCM', iv: buf(nonce), additionalData: buf(concat(utf8(BACKUP_AAD_LABEL), accountId)) },
      key,
      buf(accountCode),
    ),
  );
  return `${BACKUP_BEGIN}\nv1.${toBase64Url(concat(salt, nonce, ct))}\n${BACKUP_END}`;
}

/** The block's payload, wherever it sits in pasted text (an email body, a forwarded copy). */
export function backupPayload(text: string): Uint8Array {
  const at = text.indexOf(BACKUP_BEGIN);
  const end = text.indexOf(BACKUP_END, at + 1);
  if (at < 0 || end < 0) throw new BackupError('No NIDO RECOVERY CODE block was found.');
  const inner = text.slice(at + BACKUP_BEGIN.length, end).replace(/\s+/g, '');
  if (!inner.startsWith('v1.')) throw new BackupError('This recovery code block is not version 1.');
  const payload = fromBase64Url(inner.slice(3));
  if (payload.length !== SALT_LEN + NONCE_LEN + CODE_LEN + 16) throw new BackupError('This recovery code block is damaged.');
  return payload;
}

/** `account_code` from an (a) block, or a `BackupError` for a wrong passphrase, account or block. */
export async function decryptBackup(text: string, passphrase: string, accountId: Uint8Array): Promise<Uint8Array> {
  if (accountId.length !== 32) throw new BackupError('an account contract id is 32 octets');
  const payload = backupPayload(text);
  const salt = payload.subarray(0, SALT_LEN);
  const nonce = payload.subarray(SALT_LEN, SALT_LEN + NONCE_LEN);
  const ct = payload.subarray(SALT_LEN + NONCE_LEN);
  const key = await backupKey(normalizePassphrase(passphrase), salt);
  try {
    return new Uint8Array(
      await crypto.subtle.decrypt(
        { name: 'AES-GCM', iv: buf(nonce), additionalData: buf(concat(utf8(BACKUP_AAD_LABEL), accountId)) },
        key,
        buf(ct),
      ),
    );
  } catch {
    throw new BackupError('The passphrase is wrong, or this recovery code belongs to another Nido.');
  }
}

const BASE32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

/** (b): the 16 octets as 26 base32 characters, in groups of four. */
export function recoveryKitCode(accountCode: Uint8Array): string {
  if (accountCode.length !== CODE_LEN) throw new BackupError('account_code is 16 octets');
  let bits = 0;
  let acc = 0;
  let out = '';
  for (const b of accountCode) {
    acc = (acc << 8) | b;
    bits += 8;
    while (bits >= 5) {
      bits -= 5;
      out += BASE32[(acc >> bits) & 31];
    }
    acc &= (1 << bits) - 1;
  }
  out += BASE32[(acc << (5 - bits)) & 31];
  return out.match(/.{1,4}/g)!.join(' ');
}

/** The 16 octets of a typed or pasted recovery kit code; spaces, dashes and case are forgiven, nothing else. */
export function parseRecoveryKitCode(text: string): Uint8Array {
  const s = text.replace(/[\s-]+/g, '').toUpperCase();
  if (!/^[A-Z2-7]{26}$/.test(s)) throw new BackupError('A recovery code is 26 letters and digits (2 to 7).');
  let acc = 0;
  let bits = 0;
  const out: number[] = [];
  for (const c of s) {
    acc = (acc << 5) | BASE32.indexOf(c);
    bits += 5;
    if (bits >= 8) {
      bits -= 8;
      out.push((acc >> bits) & 0xff);
    }
    acc &= (1 << bits) - 1;
  }
  if (acc !== 0) throw new BackupError('This recovery code has a typo (its last character does not fit).');
  return Uint8Array.from(out);
}
