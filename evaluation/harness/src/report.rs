//! `nido-eval report`: the cost-bound fit and the README's result tables,
//! from the files `just eval` writes to `evaluation/results/`.
//!
//! The fit pairs each `pass` cost point with its `fail` twin (same stored
//! grant, contexts of the same shape, first caveat failing): the difference
//! in CPU instructions is the evaluator's own work, and the difference in the
//! Lean step counts is the work the model counts. The per-step constant is the
//! least-squares slope through the origin of the first on the second.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde::Serialize;
use serde_json::Value;

use crate::record;

/// The README region the report rewrites.
const BEGIN: &str = "<!-- results:begin (generated by `nido-eval report`; do not edit) -->";
const END: &str = "<!-- results:end -->";

/// Pairs whose step difference is smaller than this are left out of the
/// per-sweep ranges (both checks then do nearly the same work, so the ratio
/// is noise); the fit uses every pair.
const MIN_STEPS: i64 = 10;

/// Per case: native times, component times and their ratios, over runs.
type BenchRuns = (Vec<f64>, Vec<f64>, Vec<f64>);
/// Per case: calls per run, calls per second and µs per call, over runs.
type ThroughputRuns = (u64, Vec<f64>, Vec<f64>);

#[derive(Serialize)]
struct CostRow {
    id: String,
    sweep: String,
    variant: String,
    caveats: u64,
    contexts: u64,
    arg_bytes: u64,
    list_len: u64,
    cpu_instructions: u64,
    mem_bytes: u64,
    contract_allowed: bool,
    native_allowed: bool,
    lean_allowed: bool,
    lean_steps: u64,
    lean_bound: u64,
}

#[derive(Serialize)]
struct Pair {
    id: String,
    sweep: String,
    cpu_difference: i64,
    step_difference: i64,
    instructions_per_step: Option<f64>,
}

#[derive(Serialize)]
struct SweepFit {
    sweep: String,
    instructions_per_step_min: f64,
    instructions_per_step_max: f64,
    /// `(cpu - zero-caveat cpu) / (instructions per step * Lean bound)` at
    /// the sweep's smallest and largest parameter, and its largest value,
    /// over the `pass` points with a caveat.
    share_of_bound_first: f64,
    share_of_bound_last: f64,
    share_of_bound_max: f64,
}

#[derive(Serialize)]
struct Fit {
    instructions_per_step: f64,
    r_squared: f64,
    pairs: usize,
    zero_caveat_cpu: u64,
    /// The largest share of the bound over every `pass` point with a caveat.
    share_of_bound_max: f64,
    verdicts_agree: bool,
    sweeps: Vec<SweepFit>,
}

fn u(v: &Value, k: &str) -> u64 {
    v[k].as_u64().unwrap_or(0)
}

fn s(v: &Value, k: &str) -> String {
    v[k].as_str().unwrap_or_default().to_owned()
}

#[allow(clippy::cast_precision_loss)]
fn f(n: i64) -> f64 {
    n as f64
}

/// `1234567` as `1,234,567`.
fn thousands(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// The range of `values`; with no decimals, as whole numbers with
/// thousands separators.
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn range(values: &[f64], decimals: usize) -> String {
    let lo = values.iter().copied().fold(f64::INFINITY, f64::min);
    let hi = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    let one = |v: f64| {
        if decimals == 0 {
            thousands(v.round() as u64)
        } else {
            format!("{v:.decimals$}")
        }
    };
    if (hi - lo).abs() < f64::EPSILON {
        one(lo)
    } else {
        format!("{}–{}", one(lo), one(hi))
    }
}

fn cost_rows(dir: &Path) -> Result<Vec<CostRow>, String> {
    let points = record::read(dir, "soroban-costs.json")?;
    let cases = record::read(dir, "lean-cases.json")?;
    let native: BTreeMap<String, bool> = cases["cases"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|c| (s(c, "id"), c["native_allowed"].as_bool().unwrap_or(false)))
        .collect();
    let path = dir.join("lean-steps.jsonl");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let lean: BTreeMap<String, Value> = text
        .lines()
        .filter_map(|l| serde_json::from_str::<Value>(l).ok())
        .map(|v| (s(&v, "id"), v))
        .collect();
    points
        .as_array()
        .ok_or("soroban-costs.json is not a list")?
        .iter()
        .map(|p| {
            let id = s(p, "id");
            let l = lean
                .get(&id)
                .ok_or_else(|| format!("{id}: no Lean result"))?;
            Ok(CostRow {
                sweep: s(p, "sweep"),
                variant: s(p, "variant"),
                caveats: u(p, "caveats"),
                contexts: u(p, "contexts"),
                arg_bytes: u(p, "arg_bytes"),
                list_len: u(p, "list_len"),
                cpu_instructions: u(p, "cpu_instructions"),
                mem_bytes: u(p, "mem_bytes"),
                contract_allowed: p["allowed"].as_bool().unwrap_or(false),
                native_allowed: native.get(&id).copied().unwrap_or(false),
                lean_allowed: l["allowed"].as_bool().unwrap_or(false),
                lean_steps: u(l, "steps"),
                lean_bound: u(l, "bound"),
                id,
            })
        })
        .collect()
}

#[allow(clippy::cast_possible_wrap, clippy::cast_precision_loss)]
fn fit(rows: &[CostRow]) -> (Fit, Vec<Pair>) {
    let by_id: BTreeMap<&str, &CostRow> = rows.iter().map(|r| (r.id.as_str(), r)).collect();
    let mut pairs = Vec::new();
    for r in rows.iter().filter(|r| r.variant == "pass") {
        let Some(fail) = by_id.get(r.id.replace("-pass", "-fail").as_str()) else {
            continue;
        };
        let cpu = r.cpu_instructions as i64 - fail.cpu_instructions as i64;
        let steps = r.lean_steps as i64 - fail.lean_steps as i64;
        pairs.push(Pair {
            id: r.id.clone(),
            sweep: r.sweep.clone(),
            cpu_difference: cpu,
            step_difference: steps,
            instructions_per_step: (steps >= MIN_STEPS).then(|| f(cpu) / f(steps)),
        });
    }
    let sxy: f64 = pairs
        .iter()
        .map(|p| f(p.cpu_difference) * f(p.step_difference))
        .sum();
    let sxx: f64 = pairs.iter().map(|p| f(p.step_difference).powi(2)).sum();
    let k = sxy / sxx;
    let mean = pairs.iter().map(|p| f(p.cpu_difference)).sum::<f64>() / pairs.len() as f64;
    let ss_res: f64 = pairs
        .iter()
        .map(|p| (f(p.cpu_difference) - k * f(p.step_difference)).powi(2))
        .sum();
    let ss_tot: f64 = pairs
        .iter()
        .map(|p| (f(p.cpu_difference) - mean).powi(2))
        .sum();
    let base = rows
        .iter()
        .find(|r| r.variant == "pass" && r.caveats == 0 && r.sweep == "caveats")
        .map_or(0, |r| r.cpu_instructions);
    let share = |r: &CostRow| (r.cpu_instructions as f64 - base as f64) / (k * r.lean_bound as f64);
    let mut names: Vec<&str> = Vec::new();
    for r in rows {
        if !names.contains(&r.sweep.as_str()) {
            names.push(&r.sweep);
        }
    }
    let mut sweeps = Vec::new();
    for name in names {
        let ks: Vec<f64> = pairs
            .iter()
            .filter(|p| p.sweep == name)
            .filter_map(|p| p.instructions_per_step)
            .collect();
        let shares: Vec<f64> = rows
            .iter()
            .filter(|r| r.sweep == name && r.variant == "pass" && r.caveats > 0)
            .map(share)
            .collect();
        sweeps.push(SweepFit {
            sweep: name.to_owned(),
            instructions_per_step_min: ks.iter().copied().fold(f64::INFINITY, f64::min),
            instructions_per_step_max: ks.iter().copied().fold(f64::NEG_INFINITY, f64::max),
            share_of_bound_first: shares.first().copied().unwrap_or(0.0),
            share_of_bound_last: shares.last().copied().unwrap_or(0.0),
            share_of_bound_max: shares.iter().copied().fold(0.0, f64::max),
        });
    }
    let all_shares = rows
        .iter()
        .filter(|r| r.variant == "pass" && r.caveats > 0)
        .map(share)
        .fold(0.0, f64::max);
    (
        Fit {
            instructions_per_step: k,
            r_squared: 1.0 - ss_res / ss_tot,
            pairs: pairs.len(),
            zero_caveat_cpu: base,
            share_of_bound_max: all_shares,
            verdicts_agree: rows.iter().all(|r| {
                r.contract_allowed == r.native_allowed && r.native_allowed == r.lean_allowed
            }),
            sweeps,
        },
        pairs,
    )
}

fn table(out: &mut String, header: &[&str], rows: &[Vec<String>]) {
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(
        out,
        "|{}|",
        header.iter().map(|_| " - ").collect::<Vec<_>>().join("|")
    );
    for r in rows {
        let _ = writeln!(out, "| {} |", r.join(" | "));
    }
    out.push('\n');
}

/// A sweep's name, its column label, and the parameter it varies.
type Sweep = (&'static str, &'static str, fn(&CostRow) -> u64);

fn cost_tables(out: &mut String, rows: &[CostRow], fit: &Fit) {
    let sweeps: [Sweep; 5] = [
        ("caveats", "Caveats", |r| r.caveats),
        (
            "arg_bytes_compared",
            "Argument bytes, compared by an `ArgEq`",
            |r| r.arg_bytes,
        ),
        (
            "arg_bytes_uncompared",
            "Argument bytes, not compared",
            |r| r.arg_bytes,
        ),
        ("contexts", "Contexts (4 caveats)", |r| r.contexts),
        ("contract_list", "`ContractIn` list length", |r| r.list_len),
    ];
    for (sweep, label, param) in sweeps {
        let _ = writeln!(out, "**{label}** (`{sweep}`)\n");
        let rows: Vec<Vec<String>> = rows
            .iter()
            .filter(|r| r.sweep == sweep && r.variant == "pass")
            .map(|r| {
                let fail = rows
                    .iter()
                    .find(|x| x.id == r.id.replace("-pass", "-fail"))
                    .map_or("–".to_owned(), |x| thousands(x.cpu_instructions));
                vec![
                    param(r).to_string(),
                    thousands(r.cpu_instructions),
                    thousands(r.mem_bytes),
                    fail,
                    thousands(r.lean_steps),
                    thousands(r.lean_bound),
                ]
            })
            .collect();
        table(
            out,
            &[
                label,
                "CPU instructions",
                "Memory bytes",
                "CPU, first caveat failing",
                "Lean steps",
                "Lean bound",
            ],
            &rows,
        );
    }
    let _ = writeln!(out, "**Fit**\n");
    let _ = writeln!(
        out,
        "Over {} pairs: {:.1} CPU instructions per Lean step (least squares through the origin, R² = {:.4}). \
         Lean, the native evaluator and the contract {} on every verdict. \
         The zero-caveat check costs {} instructions. Over every point with a caveat, the whole check's cost above that, \
         as a share of the bound priced at the fitted constant (`(CPU − {}) / ({:.1} × bound)`), is at most {:.3}.\n",
        fit.pairs,
        fit.instructions_per_step,
        fit.r_squared,
        if fit.verdicts_agree { "agree" } else { "DISAGREE" },
        thousands(fit.zero_caveat_cpu),
        thousands(fit.zero_caveat_cpu),
        fit.instructions_per_step,
        fit.share_of_bound_max
    );
    let rows: Vec<Vec<String>> = fit
        .sweeps
        .iter()
        .map(|s| {
            let k = if s.instructions_per_step_min.is_finite() {
                if (s.instructions_per_step_max - s.instructions_per_step_min).abs() < 0.05 {
                    format!("{:.1}", s.instructions_per_step_min)
                } else {
                    format!(
                        "{:.1}–{:.1}",
                        s.instructions_per_step_min, s.instructions_per_step_max
                    )
                }
            } else {
                "–".to_owned()
            };
            vec![
                format!("`{}`", s.sweep),
                k,
                format!("{:.3}", s.share_of_bound_first),
                format!("{:.3}", s.share_of_bound_last),
                format!("{:.3}", s.share_of_bound_max),
            ]
        })
        .collect();
    table(
        out,
        &[
            "Sweep",
            "CPU instructions per Lean step (pairs ≥ 10 steps apart)",
            "Share of the bound, smallest parameter",
            "Share of the bound, largest parameter",
            "Largest share of the bound",
        ],
        &rows,
    );
}

fn attack_table(out: &mut String, rows: &Value) {
    let rows: Vec<Vec<String>> = rows
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|r| {
            let control = r["control"].as_bool().unwrap_or(false);
            let outcome = s(r, "outcome");
            vec![
                format!("`{}`", s(r, "id")),
                s(r, "attempt"),
                if outcome == "allowed" {
                    if control {
                        "allowed (control)".into()
                    } else {
                        "**ALLOWED**".into()
                    }
                } else {
                    s(r, "component")
                },
                s(r, "error").replace('|', "\\|"),
                if outcome == "allowed" && control {
                    "–".into()
                } else if r["state_unchanged"].as_bool().unwrap_or(false) {
                    "yes".into()
                } else {
                    format!("**no**: {}", r["changes"])
                },
            ]
        })
        .collect();
    table(
        out,
        &[
            "Attempt",
            "What the agent tries",
            "Refused by",
            "Error",
            "State unchanged",
        ],
        &rows,
    );
}

fn summary(out: &mut String, sets: &[(&str, &Value)]) {
    let mut rows = Vec::new();
    for (boundary, set) in sets {
        let mut by: BTreeMap<String, (usize, usize, usize, usize)> = BTreeMap::new();
        for r in set.as_array().cloned().unwrap_or_default() {
            let e = by.entry(s(&r, "category")).or_default();
            if r["control"].as_bool().unwrap_or(false) {
                e.3 += 1;
                continue;
            }
            e.0 += 1;
            if s(&r, "outcome") == "refused" {
                e.1 += 1;
            }
            if r["state_unchanged"].as_bool().unwrap_or(false) {
                e.2 += 1;
            }
        }
        for (cat, (n, refused, clean, controls)) in by {
            rows.push(vec![
                (*boundary).to_owned(),
                cat,
                n.to_string(),
                refused.to_string(),
                clean.to_string(),
                controls.to_string(),
            ]);
        }
    }
    table(
        out,
        &[
            "Boundary",
            "Category",
            "Attacks",
            "Refused",
            "State unchanged",
            "Allowed controls",
        ],
        &rows,
    );
}

fn workload_tables(out: &mut String, soroban: &Value, host: &Value) {
    let rows: Vec<Vec<String>> = soroban
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|r| {
            vec![
                s(r, "workload"),
                s(r, "agent"),
                s(r, "action"),
                s(r, "expected"),
                if s(r, "outcome") == "allowed" {
                    "allowed".into()
                } else {
                    s(r, "error")
                },
                u(r, "contexts").to_string(),
                thousands(u(r, "cpu_instructions")),
                match r["state_unchanged_if_refused"].as_bool() {
                    Some(true) => "yes".into(),
                    Some(false) => "**no**".into(),
                    None => "–".into(),
                },
            ]
        })
        .collect();
    let _ = writeln!(
        out,
        "**Soroban simulation** (each call is one transaction through the account)\n"
    );
    table(
        out,
        &[
            "Workload",
            "Agent",
            "Call",
            "Expected",
            "Outcome",
            "Contexts",
            "CPU instructions",
            "Unchanged if refused",
        ],
        &rows,
    );
    let rows: Vec<Vec<String>> = host
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|r| {
            let detail = s(r, "detail");
            let short: String = detail.chars().take(80).collect();
            vec![
                u(r, "step").to_string(),
                s(r, "expected"),
                s(r, "outcome"),
                short.replace('|', "\\|"),
                u(r, "micros").to_string(),
            ]
        })
        .collect();
    let _ = writeln!(
        out,
        "**Agent host** (the research agent and its summarizer)\n"
    );
    table(out, &["Step", "Expected", "Outcome", "Detail", "µs"], &rows);
}

fn bench_tables(out: &mut String, bench: &Value, throughput: &Value) {
    let runs = bench.as_array().cloned().unwrap_or_default();
    let mut cases: BTreeMap<String, BenchRuns> = BTreeMap::new();
    let mut order = Vec::new();
    let mut instantiate = Vec::new();
    for run in &runs {
        instantiate.push(run["instantiate_ms"].as_f64().unwrap_or(0.0));
        for row in run["rows"].as_array().cloned().unwrap_or_default() {
            let case = s(&row, "case");
            if !order.contains(&case) {
                order.push(case.clone());
            }
            let n = row["native_ns"].as_f64().unwrap_or(0.0);
            let c = row["component_ns"].as_f64().unwrap_or(0.0);
            let e = cases.entry(case).or_default();
            e.0.push(n);
            e.1.push(c);
            e.2.push(c / n);
        }
    }
    let iterations = runs.first().map_or(0, |r| u(r, "iterations"));
    let _ = writeln!(
        out,
        "**Per check, native `grant-eval` against the evaluator component** ({} runs of {} iterations; range over the runs; compiling and instantiating the component took {} ms)\n",
        runs.len(),
        thousands(iterations),
        range(&instantiate, 0)
    );
    let rows: Vec<Vec<String>> = order
        .iter()
        .map(|case| {
            let (n, c, ratio) = &cases[case];
            let per_second: Vec<f64> = c.iter().map(|ns| 1e9 / ns).collect();
            vec![
                case.clone(),
                format!("{} ns", range(n, 1)),
                format!(
                    "{} µs",
                    range(&c.iter().map(|x| x / 1000.0).collect::<Vec<_>>(), 2)
                ),
                format!("{}x", range(ratio, 0)),
                range(&per_second, 0),
            ]
        })
        .collect();
    table(
        out,
        &[
            "Case",
            "Native",
            "Component",
            "Ratio",
            "Component checks per second",
        ],
        &rows,
    );

    let runs = throughput.as_array().cloned().unwrap_or_default();
    let mut cases: BTreeMap<String, ThroughputRuns> = BTreeMap::new();
    let mut order = Vec::new();
    for run in &runs {
        for row in run.as_array().cloned().unwrap_or_default() {
            let case = s(&row, "case");
            if !order.contains(&case) {
                order.push(case.clone());
            }
            let e = cases.entry(case).or_default();
            e.0 = u(&row, "calls");
            e.1.push(row["calls_per_second"].as_f64().unwrap_or(0.0));
            e.2.push(row["micros_per_call"].as_f64().unwrap_or(0.0));
        }
    }
    let _ = writeln!(
        out,
        "**Agent-host tool calls** (one agent, calls in sequence; {} runs; range over the runs)\n",
        runs.len()
    );
    let rows: Vec<Vec<String>> = order
        .iter()
        .map(|case| {
            let (calls, per_second, micros) = &cases[case];
            vec![
                case.clone(),
                thousands(*calls),
                range(per_second, 0),
                range(micros, 2),
            ]
        })
        .collect();
    table(
        out,
        &[
            "Tool call",
            "Calls per run",
            "Calls per second",
            "µs per call",
        ],
        &rows,
    );
}

fn machine(out: &mut String, m: &Value) {
    let rows: Vec<Vec<String>> = m
        .as_object()
        .map(|o| {
            o.iter()
                .map(|(k, v)| {
                    vec![
                        k.clone(),
                        v.as_str().map_or_else(|| v.to_string(), str::to_owned),
                    ]
                })
                .collect()
        })
        .unwrap_or_default();
    table(out, &["", ""], &rows);
}

/// Write `cost-bound.json` and `cost-bound.csv` to `dir` and the tables into
/// `readme` between its result markers.
///
/// # Errors
///
/// If a result file is missing or the README has no result markers.
pub fn run(dir: &Path, readme: &Path) -> Result<(), String> {
    let rows = cost_rows(dir)?;
    let (fit, pairs) = fit(&rows);
    record::write(
        dir,
        "cost-bound.json",
        &serde_json::json!({ "fit": fit, "pairs": pairs }),
    )?;
    record::write_csv(dir, "cost-bound.csv", &rows)?;

    let mut out = String::new();
    let _ = writeln!(out, "{BEGIN}\n\n### Machine and versions\n");
    machine(&mut out, &record::read(dir, "machine.json")?);
    let _ = writeln!(out, "### Cost per check and the Lean bound\n");
    cost_tables(&mut out, &rows, &fit);
    let soroban_attacks = record::read(dir, "soroban-attacks.json")?;
    let host_attacks = record::read(dir, "agent-host-attacks.json")?;
    let _ = writeln!(out, "### Attack suite\n");
    summary(
        &mut out,
        &[
            ("Soroban simulation", &soroban_attacks),
            ("Agent host", &host_attacks),
        ],
    );
    let _ = writeln!(
        out,
        "**Soroban simulation: the grant signer on a factory-minted Perch account**\n"
    );
    attack_table(&mut out, &soroban_attacks);
    let _ = writeln!(out, "**Agent host**\n");
    attack_table(&mut out, &host_attacks);
    let _ = writeln!(out, "### Workloads\n");
    workload_tables(
        &mut out,
        &record::read(dir, "soroban-workloads.json")?,
        &record::read(dir, "agent-host-workload.json")?,
    );
    let _ = writeln!(out, "### Agent host: cost per check and throughput\n");
    bench_tables(
        &mut out,
        &record::read(dir, "agent-host-bench.json")?,
        &record::read(dir, "agent-host-throughput.json")?,
    );
    out.push_str(END);

    let text = std::fs::read_to_string(readme).map_err(|e| format!("{}: {e}", readme.display()))?;
    let (Some(start), Some(end)) = (text.find(BEGIN), text.find(END)) else {
        return Err(format!("{}: no result markers", readme.display()));
    };
    let updated = format!("{}{}{}", &text[..start], out, &text[end + END.len()..]);
    std::fs::write(readme, updated).map_err(|e| format!("{}: {e}", readme.display()))
}
